// @ts-check
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import starlightGiscus from 'starlight-giscus';
import { getCurriculum, trackHasPages } from './src/lib/curriculum.mjs';

const REPO = 'https://github.com/udaysingh236/senior-dev-notes';

// Comments under each topic page, stored as GitHub Discussions (https://giscus.app).
// The giscus GitHub App must be installed on the repo; giscus.app then shows the category ID.
// Until categoryId is filled in, the plugin stays off so the build never shows a broken widget.
const GISCUS = {
  repo: 'udaysingh236/senior-dev-notes',
  repoId: 'R_kgDOVNbYCA',
  category: 'Announcements', // an announcement-type category: only giscus and maintainers open threads
  categoryId: '',
  lazy: true, // load the comments iframe only when the reader scrolls near it
};

// One sidebar group per track, in CURRICULUM.md order, each autogenerated from its folder.
// Tracks with no pages yet are left out so the sidebar never shows empty groups;
// the roadmap page lists everything that is planned.
const trackGroups = getCurriculum()
  .tracks.filter((track) => trackHasPages(track.folder))
  .map((track) => ({
    label: track.title,
    collapsed: false,
    items: [{ autogenerate: { directory: track.folder } }],
  }));

// https://astro.build/config
export default defineConfig({
  site: 'https://seniordevnotes.netlify.app',
  integrations: [
    starlight({
      title: 'Senior Dev Notes',
      description:
        'System design and production engineering for beginners, explained the way a senior engineer mentors a junior.',
      favicon: '/favicon.svg',
      social: [{ icon: 'github', label: 'GitHub', href: REPO }],
      editLink: { baseUrl: `${REPO}/edit/main/` },
      lastUpdated: true,
      customCss: ['./src/styles/custom.css'],
      tableOfContents: { minHeadingLevel: 2, maxHeadingLevel: 3 },
      plugins: GISCUS.categoryId ? [starlightGiscus(GISCUS)] : [],
      components: {
        PageTitle: './src/components/TopicHeader.astro',
      },
      sidebar: [
        {
          label: 'Start here',
          items: [
            { label: 'Home', link: '/' },
            { label: 'Roadmap', slug: 'roadmap' },
            { label: 'About', slug: 'about' },
          ],
        },
        ...trackGroups,
      ],
    }),
  ],
});
